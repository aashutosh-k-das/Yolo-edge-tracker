"""Phase 2b - hyper-parameter tuning with Ultralytics' genetic-evolution tuner.

Each iteration mutates the hyper-parameters, trains for a few epochs, and keeps the fittest set
(fitness = val mAP50-95). The search space below is restricted to ranges that make sense for
aerial footage: e.g. no 45-degree rotations, no upside-down flips for ground cameras.

    python train/tune.py --iterations 30 --epochs 20 --fraction 0.5      # ~ overnight on a T4
    python train/tune.py ... --resume                                    # continue after a disconnect
    python train/train.py --hyp train/hyp_tuned.yaml --name v8n_640_tuned

Budget = iterations x epochs short trainings. Time ONE epoch of train.py first and multiply.
Rule of thumb: 30 x 20 epochs on 50% of the data finds most of the gain. Tuning on more data
or more epochs is better but slower.
"""
import argparse
import glob
import os

import yaml
from ultralytics import YOLO

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# (min, max[, mutation gain]) - starting values come from the --hyp preset.
SPACE = {
    # optimiser
    "lr0": (1e-4, 1e-2),
    "lrf": (0.01, 0.5),
    "momentum": (0.8, 0.98, 0.3),
    "weight_decay": (0.0, 0.001),
    "warmup_epochs": (0.0, 5.0),
    # loss weights: `box` matters for tight boxes on tiny drones, `cls` for drone/aircraft confusion
    "box": (3.0, 15.0),
    "cls": (0.2, 2.0),
    "dfl": (0.5, 3.0),
    # augmentation (narrow, aerial-plausible ranges)
    "hsv_s": (0.2, 0.9),
    "hsv_v": (0.2, 0.7),
    "degrees": (0.0, 10.0),
    "translate": (0.0, 0.25),
    "scale": (0.2, 0.6),
    "mosaic": (0.5, 1.0),
    "mixup": (0.0, 0.2),
}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", default="yolov8n.pt")
    ap.add_argument("--data", default=os.path.join(ROOT, "data", "dataset.yaml"))
    ap.add_argument("--hyp", default=os.path.join(ROOT, "train", "hyp_surveillance.yaml"), help="starting point")
    ap.add_argument("--iterations", type=int, default=30)
    ap.add_argument("--epochs", type=int, default=20, help="epochs per iteration")
    ap.add_argument("--imgsz", type=int, default=640)
    ap.add_argument("--batch", type=int, default=32)
    ap.add_argument("--fraction", type=float, default=0.5, help="fraction of train set per iteration")
    ap.add_argument("--optimizer", default="SGD", choices=["SGD", "AdamW"],
                    help="must be explicit: optimizer=auto ignores lr0/momentum")
    ap.add_argument("--project", default=os.path.join(ROOT, "runs", "tune"))
    ap.add_argument("--name", default="v8n_tune")
    ap.add_argument("--resume", action="store_true")
    ap.add_argument("--out", default=os.path.join(ROOT, "train", "hyp_tuned.yaml"))
    a = ap.parse_args()

    with open(a.hyp) as f:
        base = yaml.safe_load(f) or {}
    base.pop("optimizer", None)
    space = dict(SPACE)
    if base.get("flipud", 0) > 0:          # only search vertical flips for top-down presets
        space["flipud"] = (0.0, 0.5)

    # close_mosaic from a 150-epoch preset would switch mosaic off for most of a 20-epoch trial
    tune_args = dict(base, close_mosaic=min(base.get("close_mosaic", 10), max(a.epochs // 5, 1)))

    print("Tuning {} params for {} iterations x {} epochs (fraction={})".format(
        len(space), a.iterations, a.epochs, a.fraction))
    YOLO(a.model).tune(
        data=a.data, epochs=a.epochs, iterations=a.iterations, imgsz=a.imgsz, batch=a.batch,
        fraction=a.fraction, optimizer=a.optimizer, space=space, cache="ram", amp=True,
        plots=False, save=False, val=False,   # val only on each trial's final epoch -> faster
        project=a.project, name=a.name, resume=a.resume, **tune_args
    )

    found = sorted(glob.glob(os.path.join(a.project, a.name + "*", "best_hyperparameters.yaml")),
                   key=os.path.getmtime)
    if not found:
        raise SystemExit("No best_hyperparameters.yaml found under {}".format(a.project))
    with open(found[-1]) as f:
        best = yaml.safe_load(f)

    tuned = dict(base)                         # keep preset-only keys (close_mosaic, flips, ...)
    tuned.update({k: best[k] for k in space if k in best})
    tuned["optimizer"] = a.optimizer
    with open(a.out, "w") as f:
        f.write("# Generated by train/tune.py from {}\n# base preset: {}\n".format(
            found[-1], os.path.basename(a.hyp)))
        yaml.safe_dump(tuned, f, sort_keys=False)
    print("\nTuned hyper-parameters -> {}".format(a.out))
    print("Tuning curves: {}".format(os.path.join(os.path.dirname(found[-1]), "tune_fitness.png")))
    print("Next: python train/train.py --hyp {} --name v8n_640_tuned".format(os.path.relpath(a.out, ROOT)))


if __name__ == "__main__":
    main()
